def main():
    built = []
    for subject, table, jp in (("science", SCIENCE, "理科"),
                               ("social", SOCIAL, "社会")):
        for band, rows in table.items():
            p = Pack("%s/ana-%s" % (subject, BAND_CODE[band]), subject,
                     "穴埋め %s %s" % (jp, band), [band],
                     "文の空欄を4択で埋める。誤答は同じ文に入れそうな語にしてある")
            for q, ok, wrong, note, unit in rows:
                p.Q(q, ok, list(wrong), band, note, unit=unit)
            built.append(p.write())
    report(built)
    return 0


if __name__ == "__main__":
    sys.exit(main())
