"""図 ―― 理科・社会の「図を見て答える」問題で使う絵。

    python3 app/tools/gen_figures.py

なぜ画像ファイルにしないか
--------------------------
写真やPNGを置くと、置き場・配信・CSP（img-src）・容量・オフライン保存の
5つを同時に相手にすることになる。図で問いたいのは**形と位置**だけで、
写真の情報量は要らない。だから絵は SVG を**教材の中に直接書く**。

  ・置き場が要らない（教材ファイルと同じ経路で配られる）
  ・CSP を弱めなくてよい（絵は markup であって外部資源ではない）
  ・地下鉄の中でも出る（教材と一緒に端末に入っている）
  ・紙に刷っても、拡大しても、にじまない
  ・黒い画面でも白い紙でも同じものが使える（色を currentColor にする）

答えを絵の中に書かない
----------------------
部位には **ア・イ・ウ・エ** の印だけを置く。名前を書いてしまうと、
「アの名前は？」と聞いた瞬間に答えが絵に書いてあることになる。
日本の理科のテストがこの形をとっているのは、それが理由である。

安全について
------------
この SVG は画面に markup として差し込まれる。教材は自分たちで
生成したものだけだが、**差し込む以上は形を検査する**。
使ってよいタグと属性を名指しで持ち、それ以外が1つでもあれば
書き出さない（script、on…、href、style は通さない）。

典拠
----
花のつくり・こん虫のからだ・回路・てこ・消化・等高線は事実であり、
事実に著作権はない。**線は全部ここで引いている。** 図版の転載はない。
"""

