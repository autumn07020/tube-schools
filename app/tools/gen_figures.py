# 使ってよいタグ。**名指しで持つ。**
OK_TAGS = {"svg", "g", "path", "line", "circle", "ellipse", "rect",
           "polyline", "polygon", "text", "tspan"}
# 使ってよい属性。style も href も通さない（外を見に行かせない）。
OK_ATTRS = {"viewBox", "xmlns", "d", "x", "y", "x1", "y1", "x2", "y2",
            "cx", "cy", "r", "rx", "ry", "width", "height", "points",
            "fill", "stroke", "stroke-width", "stroke-linecap",
            "stroke-linejoin", "stroke-dasharray", "font-size",
            "text-anchor", "transform", "class", "dy", "opacity"}
TAG_RE = re.compile(r"<\s*/?\s*([a-zA-Z][a-zA-Z0-9-]*)")
ATTR_RE = re.compile(r"([a-zA-Z-]+)\s*=")


def check_svg(name, svg):
    """形を確かめる。1つでも知らないものがあれば止める。"""
    if not svg.startswith("<svg ") or not svg.rstrip().endswith("</svg>"):
        raise ValueError("%s: svg で始まって svg で終わっていない" % name)
    for t in TAG_RE.findall(svg):
        if t not in OK_TAGS:
            raise ValueError("%s: 使えないタグ <%s>" % (name, t))
    for a in ATTR_RE.findall(svg):
        if a not in OK_ATTRS:
            raise ValueError("%s: 使えない属性 %s" % (name, a))
    if "viewBox" not in svg:
        raise ValueError("%s: viewBox が無い（拡大でつぶれる）" % name)
    low = svg.lower()
    for bad in ("script", "javascript:", "onload", "onclick", "<image", "xlink"):
        if bad in low:
            raise ValueError("%s: 危ないもの %s" % (name, bad))


