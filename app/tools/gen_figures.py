def _climate():
    # 月ごとの気温（折れ線）と降水量（棒）。**日本海側の型**にしてある。
    temp = [3, 4, 7, 13, 18, 22, 26, 27, 23, 17, 11, 6]
    rain = [280, 190, 160, 130, 130, 150, 220, 180, 200, 170, 230, 300]
    out = ['<svg viewBox="0 0 340 230" xmlns="http://www.w3.org/2000/svg">']
    x0, y0, w, h = 40, 190, 264, 140
    out.append('<path d="M%d %d L%d %d L%d %d" %s/>'
               % (x0, y0 - h, x0, y0, x0 + w, y0, S))
    for i, mm in enumerate(rain):
        bw = 14
        bh = mm * h / 320.0
        out.append('<rect x="%d" y="%d" width="%d" height="%d" %s/>'
                   % (x0 + 6 + i * 22, y0 - bh, bw, bh, S))
    pts = " ".join("%d,%d" % (x0 + 13 + i * 22, y0 - (t + 5) * h / 40.0)
                   for i, t in enumerate(temp))
    out.append('<polyline points="%s" %s/>' % (pts, S))
    for i, t in enumerate(temp):
        out.append('<circle cx="%d" cy="%.0f" r="3" fill="currentColor"/>'
                   % (x0 + 13 + i * 22, y0 - (t + 5) * h / 40.0))
    out.append('<text x="%d" y="%d" %s>1月</text>' % (x0 + 13, y0 + 18, TS))
    out.append('<text x="%d" y="%d" %s>7月</text>' % (x0 + 13 + 6 * 22, y0 + 18, TS))
    out.append('<text x="%d" y="%d" %s>12月</text>' % (x0 + 13 + 11 * 22, y0 + 18, TS))
    out.append('<text x="%d" y="%d" %s>降水量</text>' % (x0 - 4, y0 - h - 6, TS))
    out.append('<text x="%d" y="%d" %s>気温</text>' % (x0 + w - 10, y0 - h - 6, TS))
    out.append('<text x="170" y="222" %s>ある都市の 気温と降水量</text>' % TS)
    out.append('</svg>')
    return "".join(out)


FIG["climate"] = _climate()


