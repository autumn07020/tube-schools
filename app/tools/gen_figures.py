def mark(x, y, ch):
    """ア・イ・ウ・エ の丸印。"""
    return ('<circle cx="%d" cy="%d" r="12" fill="none" stroke="currentColor"'
            ' stroke-width="2"/><text x="%d" y="%d" %s>%s</text>'
            % (x, y, x, y + 5, T, ch))


def lead(x1, y1, x2, y2):
    """印から部位へ引く細い線。"""
