BAND_CODE = {"小4": "e4", "小5": "e5", "小6": "e6",
             "中1": "j1", "中2": "j2", "中3": "j3"}


def main():
    built = []
    for band, rows in KAKI.items():
        p = Pack("japanese/kaki-" + BAND_CODE[band], "japanese",
                 "漢字の書き %s" % band, [band],
                 "文から漢字を書く。答えは大きく出す")
        for yomi, kanji, sent, hint in rows:
            # 表は「文（空欄つき）と読み」。裏は漢字だけ ―― 大きく出すため。
            p.T("%s（%s）" % (sent.replace("○", "＿＿"), yomi),
                kanji, band, hint, "", "")
        built.append(p.write())
    report(built)
    return 0


if __name__ == "__main__":
    sys.exit(main())
