def build():
    out = []
    for pid, name, bands, data, note in GRADES:
        p = Pack(pid, "japanese", name, bands, note)
        band = bands[0]
        for word, yomi, wrong, meaning in data:
            # 差し替え待ちの行（意味が "-"）は入れない
            if meaning == "-" or wrong == "-":
                continue
            p.Q("「%s」の読みは？" % word, yomi, wrong, band, meaning)
            p.T(word, yomi, band, meaning)
        out.append(p.write())
    return out


