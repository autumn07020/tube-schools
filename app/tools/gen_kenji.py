def esc(s):
    return (s.replace("\\", "\\\\").replace('"', '\\"')
             .replace("\r", " ").replace("\n", "\\n"))


def main():
    # 1. 本文を content/readings.js に足す（既にあるものは残す）
    path = os.path.join(CONTENT, "readings.js")
    src = io.open(path, encoding="utf-8").read()
    lines = []
    for g, (title, text) in sorted(BUN.items()):
        lines.append('"kenji-%s":"%s",' % (g, esc(text)))
    keep = [l for l in src.split("\n") if not l.startswith('"kenji-')]
    i = keep.index("global.TubeReadings = {")
    out = keep[:i + 1] + lines + keep[i + 1:]
    io.open(path, "w", encoding="utf-8").write("\n".join(out))

    # 2. 設問のパック
    built, packs = [], {}
    for g, q, ok, wrong, note, unit in Q:
        if g not in packs:
            packs[g] = Pack("japanese/kenji-" + g, "japanese",
                            "文学の読解 %s" % BAND[g], [BAND[g]],
                            "宮沢賢治（青空文庫・著作権消滅）。設問は書き下ろし")
        packs[g].Q(q, ok, list(wrong), BAND[g], note, unit=unit,
                   bun="kenji-" + g)
    for g in sorted(packs):
        built.append(packs[g].write())
    report(built)
    print("\n  本文 %d本（%d字）／ %s"
          % (len(BUN), sum(len(t) for _, t in BUN.values()),
             "、".join("%s %s" % (BAND[g], BUN[g][0]) for g in sorted(BUN))))
    return 0


if __name__ == "__main__":
    sys.exit(main())
