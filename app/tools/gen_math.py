    p.unit = ""
    B = "中1"

    # 取り戻した手書き分。帯は「基礎／標準」で書かれているので、
    # このパックの帯（中1）にそろえる。
    for front, back, _band, note in J1_TERMS:
        p.T(front, back, B, note)
    # 取り戻した手書き問題にも単元名を付ける。問題文の言葉で割りあてる ――
    # もとの教材は単元を持っていなかったので、ここで足すしかない。
    J1_UNIT = [
        ("絶対値", "正負の数"), ("²", "正負の数"), ("÷", "正負の数"),
        ("a −", "文字式"), ("a +", "文字式"), ("代入", "文字式"),
        ("方程式", "一次方程式"), ("= 11", "一次方程式"), ("x + 7", "一次方程式"),
        ("比例", "比例と反比例"), ("y =", "比例と反比例"),
        ("おうぎ形", "おうぎ形"), ("中央値", "資料の活用"),
        ("2直線", "空間図形"),
    ]
    for q, ok, wrong, _band, note in J1_QUIZ:
        u = ""
        for key, name in J1_UNIT:
            if key in q:
                u = name
                break
        p.Q(q, ok, wrong, B, note, unit=u or "正負の数")

    p.T("弧", "円周の一部分", B, "")

    # --- 正負の数 ---
    p.unit = "正負の数"
    for a, b, op in [(-7, 3, "+"), (5, -9, "+"), (-4, -6, "+"),
                     (-8, -3, "-"), (6, -2, "-"), (-5, 7, "-")]:
        ok = a + b if op == "+" else a - b
        # ありがちな間違い ―― 符号を無視して足す／ひく向きを逆にする／
        # 答えの符号だけ取りちがえる
        p.Q("(%s) %s (%s) を計算すると？" % (n(a), op.replace("-", MINUS), n(b)),
            n(ok), uniq(n(ok), [n(a - b if op == "+" else a + b), n(-ok),
                                n(abs(a) + abs(b)), n(abs(a) - abs(b)),
                                n(-abs(a) - abs(b)), n(abs(b) - abs(a))]),
            B, "符号に気をつける。答えは %s。" % n(ok))
    for a, b in [(-3, 8), (6, -7), (-5, -4), (-12, 3)]:
        ok = a * b
        p.Q("(%s) × (%s) を計算すると？" % (n(a), n(b)), n(ok),
            uniq(n(ok), [n(-ok), n(a + b), n(abs(a * b)), n(a - b)]),
            B, "符号は、負の数が偶数個なら +、奇数個なら −。")
    for base, e in [(-2, 2), (-2, 3), (-3, 2), (-5, 2)]:
        ok = base ** e
        sup = "²" if e == 2 else "³"
        # ありがちな間違い ―― 符号をかっこの外に出す／指数をかけ算と読む
        # **記号だけが違う問題文にしない。** 項目IDは記号を落とすので、
        # 「(−2)²」と「(−2)³」が同じIDになり、片方に答えると
