MINUS = "−"          # U+2212。ASCII の - は式の中で読みにくい


# ------------------------------------------------------------------
# 数の書き方
# ------------------------------------------------------------------
def n(x):
    """数を文字にする。負の数は数学の負号（−）で書く。"""
    if isinstance(x, Fraction):
        return frac(x)
    if isinstance(x, float):
        s = ("%.10f" % x).rstrip("0").rstrip(".")
        return s.replace("-", MINUS)
    return str(x).replace("-", MINUS)


def frac(f):
    """分数。整数になるならそのまま整数で書く。"""
    f = Fraction(f)
    if f.denominator == 1:
        return n(f.numerator)
    sign = MINUS if f < 0 else ""
    return "%s%d/%d" % (sign, abs(f.numerator), f.denominator)


def coef(a):
    """係数の書き方。1 は書かず、−1 は符号だけにする。

    「1x − 1y = −1」は数学では書かない。生徒が見て
    「これは何かの略記か」と迷う ―― 迷わせた時点で問題として悪い。
    """
    if a == 1:
        return ""
    if a == -1:
        return MINUS
    return n(a)


def uniq(ok, wrongs):
    """誤答から、正解と重複を取り除いて3つに整える。

    **足りないぶんを乱数で埋めない。** 埋めると、ありがちな間違いでない
    数が混ざり、読まなくても消せる選択肢になる。3つに満たないときは
    呼び出し側の作り方が悪いので、そこで気づけるように例外を投げる。
    """
    out = []
    for w in wrongs:
        if w == ok or w in out:
            continue
        out.append(w)
    if len(out) < 3:
        raise ValueError("誤答が %d 個しか作れません（正解 %s / %r）"
                         % (len(out), ok, wrongs))
    return out[:3]


