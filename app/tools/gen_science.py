def _key_of(pid):
    """教材IDから TERMS の鍵を引く。science/e4 → E4、science/j1n → J1。"""
    tail = pid.split("/")[-1]
    return re.sub(r"[^a-z0-9]", "", tail).upper().replace("N", "").replace("S", "") \
        if tail.startswith(("j1n", "j1s")) else tail.upper()


def build():
    out = []
    for pid, name, bands, data, note in GRADES:
        p = Pack(pid, "science", name, bands, note)
        band = bands[0]
        # 手で並べた用語カードを先に入れる（表＝用語／裏＝説明）。
        # あとから Q 由来のものが同じ用語を作らないよう、名前を控えておく。
        seen_terms = set()
        for t, d in TERMS.get(_key_of(pid), []):
            p.T(t, d, band, "用語")
            seen_terms.add(t)
        for q, ok, wrong, unit, expl in data:
            p.Q(q, ok, wrong, band, expl or unit)
            # 用語カードは答えを表にする。同じ答えの問題が複数あるので、
            # 最初の1つだけを用語にする（「二酸化炭素」が何度も出るため）。
            # 用語カードは「答えが用語になる問い」だけから作る。
            if ok not in seen_terms and is_term_question(q):
                seen_terms.add(ok)
                p.T(ok, term_card(q), band, unit)
        out.append(p.write())
    return out


if __name__ == "__main__":
    built = build()
    report(built)
    print()
    bad = False
    for b in built:
        ok = b["items"] >= 100
        bad = bad or not ok
        print("  %s %s … %d問" % ("OK " if ok else "×  ", b["name"], b["items"]))
    if bad:
        sys.exit(1)
