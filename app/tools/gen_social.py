def _key_of(pid):
    """教材IDから TERMS の鍵を引く。social/e5 → E5、social/j1s → J1。"""
    tail = pid.split("/")[-1]
    return (tail[:2] if tail.startswith(("j1s", "j2s", "j3s")) else tail).upper()

def build():
    out = []

    # --- 小4：都道府県と県庁所在地（事実）＋くらし
    p = Pack("social/e4", "social", "社会 小4", ["小4"],
             "都道府県と県庁所在地・水道とごみ・安全と災害。問題文と解説は自作")
    others = [k for k, _ in KEN]
    for i, (ken, sty) in enumerate(KEN):
        wrong = [KEN[(i + d) % len(KEN)][1] for d in (7, 17, 29)]
        p.Q("%sの県庁所在地は？" % ken, sty, wrong, "小4", "都道府県と県庁所在地")
        p.T(ken, sty, "小4", "県庁所在地")
    for q, ok, wrong, unit, expl in E4_EXTRA:
        p.Q(q, ok, wrong, "小4", expl or unit)
    out.append(p.write())

    # --- ほかの学年
    for pid, name, band, data, note in [
        ("social/e5", "社会 小5", "小5", E5, "国土と気候・農業と水産業・工業・情報・環境。問題文と解説は自作"),
        ("social/e6", "社会 小6", "小6", E6, "歴史の流れ・政治のしくみ・国際。問題文と解説は自作"),
        ("social/j1s", "社会 中1", "中1", J1, "世界の地理。問題文と解説は自作"),
        ("social/j2", "社会 中2", "中2", J2, "日本の地理と歴史。問題文と解説は自作"),
        ("social/j3", "社会 中3", "中3", J3, "近現代史・政治・経済・国際。問題文と解説は自作"),
    ]:
        p = Pack(pid, "social", name, [band], note)
        # 手で並べた用語カードを先に入れる（表＝用語／裏＝説明）
        seen = set()
        for t, d in TERMS.get(_key_of(pid), []):
            p.T(t, d, band, "用語")
            seen.add(t)
        for q, ok, wrong, unit, expl in data:
            p.Q(q, ok, wrong, band, expl or unit)
            # 用語カードは「答えが用語になる問い」だけから作る。
            if ok not in seen and is_term_question(q):
                seen.add(ok)
                p.T(ok, term_card(q), band, unit)
        out.append(p.write())
    return out


