# 用語カードにしてよいのは、**答えがそれ自体で用語になっている問い**だけ。
#
#   ○「物質が酸素と結びつく変化を何という？」→ 酸化
#       表「酸化」／裏「物質が酸素と結びつく変化」 … 用語カードとして成立する
#
#   ×「水の電気分解で発生する水素と酸素の体積比は？」→ 2対1
#       表「2対1」／裏「水の電気分解で…体積比は」 … **意味をなさない**
#
# 理科・社会の問いと答えは写像ではない。機械的に反転させると、
# 「2対1」を見せて何を思い出させたいのか分からないカードが量産される。
# 実際、理科中2では58件のうち56件がこの形になっていた。
ASK = re.compile(r"(を何という|とは何|を何とよ|の名は|を何と呼)")


def is_term_question(q):
    """答えが用語になる問いか。"""
    return bool(ASK.search(q))


def term_card(q):
    """問いから、用語の説明文をつくる。「〜を何という？」→「〜」。"""
    return ASK.sub("", q).rstrip("？?。 ").strip()


