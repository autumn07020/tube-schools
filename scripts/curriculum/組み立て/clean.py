REPL=[(a,b) for a,b in REPL if a!=b]
BAD=set("𩐳賀顔旳昀單說頻頬漬湧沓稔絵縫薬囊囗")
def pick(s):
    """'A ⇄ B ⇄ C' から1つ選ぶ：悪い字を含まない・余計な「）」が無い・最長、の順。"""
    if "⇄" not in s: return s
    cands=[c.strip() for c in s.split("⇄")]
    def score(c):
        return (sum(1 for ch in c if ch in BAD), c.count("）")-c.count("（"), -len(c))
    cands.sort(key=score); return cands[0]
def clean(s):
    s=pick(s)
    for a,b in REPL: s=s.replace(a,b)
    s=re.sub(r"^[（(）)｜|.．]+","",s); s=re.sub(r"[）)]$","",s) if s.count("）")>s.count("（") else s
    s=re.sub(r"\s+","",s)
    # 同じ語の二重化（間に丸数字が挟まることも）
    m=re.fullmatch(r"(.+?)[①-⑳\d）)]*\1",s)
    if m: s=m[1]
    s=re.sub(r"^[①-⑳]","",s)
    # 【 】の片割れ
    s=s.replace("（","【",1) if s.count("【")<s.count("】") and "（" in s and "】" in s and s.find("（")<s.find("】") and "）" not in s[s.find("（"):s.find("】")] else s
    s=re.sub(r"」$","】",s) if s.count("【")>s.count("】") else s
    s=re.sub(r"\[","【",s)
    return s
