def load(pdf,pg):
    d=json.load(open(f"{OUT}/{pdf}-p{pg:02d}.json"))
    rows=[]
    for u in d["units"]:
        unit=clean(u["unit"]); test=clean(u.get("test","")); prep=clean(u.get("prep",""))
        m=re.search(r"(新中学問題集|授業内容の復習|演習問題集|授業内演習|映像新中問|残問演習|復習確認テスト|一問一答テスト|定着度確認テスト)",unit)
        if m and m.start()>0:
            unit,rest=unit[:m.start()],unit[m.start():]
            if pdf.startswith("中1") and pg in (9,10): test=rest+test
            else: test=rest+test
        unit=re.sub(r"^[①-⑳]|^1[0-2](?=[^\d])|^[1-9](?=[）)])","",unit)
        rows.append({"unit":unit,"test":test,"prep":prep})
    for op in ROWFIX.get((pdf,pg),[]):
        if op[0]=="drop":
            rows=[r for r in rows if not r["unit"].startswith(op[1])]
        elif op[0]=="drop_dup":
            seen=False; out=[]
            for r in rows:
                if r["unit"].startswith(op[1]):
                    if seen: continue
                    seen=True
                out.append(r)
            rows=out
        elif op[0]=="drop_empty":
            rows=[r for r in rows if r["unit"]]
        elif op[0]=="insert_at":
            rows.insert(op[1],{"unit":op[2],"test":"","prep":""})
        elif op[0]=="replace_head":
            rows=[{"unit":u,"test":t,"prep":""} for u,t in op[2]]+rows[op[1]:]
    return rows
def blocks(pdf,pg):
    if (pdf,pg) in HAND:
        return [(term,[{"unit":clean(u),"test":"","prep":""} for u in us]) for term,us in HAND[(pdf,pg)]]
    rows=load(pdf,pg); sizes=SIZES[(pdf,pg)]
    need=sum(n for _,n in sizes)
    if len(rows)>need: rows=[r for r in rows if r["unit"]][:need] if len([r for r in rows if r["unit"]])>=need else rows
    if len(rows)!=need:
        print(f"!! {pdf} p{pg}: 行 {len(rows)} ≠ 期の合計 {need}", file=sys.stderr)
        for i,r in enumerate(rows): print(f"   {i:>2} {r['unit'][:40]}", file=sys.stderr)
    out=[]; i=0
    for term,n in sizes:
        blk=rows[i:i+n]; i+=n
        for k,r in enumerate(blk):
            if (term,k+1) in UNITFIX.get((pdf,pg),{}): r["unit"]=clean(UNITFIX[(pdf,pg)][(term,k+1)])
        out.append((term,blk))
    return out
