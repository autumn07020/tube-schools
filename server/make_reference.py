NAMES = {"e4": "小4", "e5": "小5", "e6": "小6", "j1": "中1", "j2": "中2", "j3": "中3"}

# 年度の始まり。日本の学校は4月第1週。長期休暇の週は授業を置かない。
YEAR_START = "2026-04-06"
BREAKS = set(range(16, 21)) | set(range(38, 41))   # 夏期・冬期のおおよその週


def build(year_start=YEAR_START):
    base = time.mktime(time.strptime(year_start, "%Y-%m-%d"))
    made = []
    for grade, subjects in UNITS.items():
        # 教科ごとの単元を、週に均等に散らす。
        # 1週に複数教科が来るのが実際の時間割に近い。
        weeks = {}
        for subject, units in subjects.items():
            n = len(units)
            if not n:
                continue
            # 授業のある週だけに割り付ける
            usable = [w for w in range(1, 44) if w not in BREAKS]
            step = max(1, len(usable) // n)
            for i, unit in enumerate(units):
                w = usable[min(i * step, len(usable) - 1)]
                weeks.setdefault(w, []).append({"subject": subject, "unit": unit})
        data = {
            "grade": grade,
            "name": NAMES.get(grade, grade),
            "source": SOURCE,
            "provisional": True,        # ★ 仮置きであることを持たせる
            "year": time.localtime(base).tm_year,
            "importedAt": int(time.time()),
            "weeks": [
                {"w": w,
                 "from": time.strftime("%Y-%m-%d", time.localtime(base + (w - 1) * 7 * 86400)),
                 "units": weeks[w]}
                for w in sorted(weeks)
            ],
        }
        refcur.save_reference(grade, data)
        n_units = sum(len(x["units"]) for x in data["weeks"])
        made.append((grade, data["name"], len(data["weeks"]), n_units))
    return made


